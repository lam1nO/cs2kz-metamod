#pragma once
// Приведение чат-команд без «!» к форме «!команда». Чистые функции без SDK — host-тест
// tests/chat_trigger_test.cpp.
//
// Игроки пишут команды тремя способами кроме «!»: через точку (в русской раскладке «.»
// стоит на клавише «/»), вовсе без префикса («maptop», «RTV») и через «/». «/» и «!» и так
// понимают и форк, и CSSharp. Точку и голое слово переписываем в «!слово ...» ДО всех
// обработчиков say — дальше строка идёт ровно тем же путём, что набранная через «!»:
// команды форка, CSSharp-плагины (Host_Say видит тот же CCommand), скрытие из чата.
#include <cstddef>

namespace chattrigger
{
	enum Form
	{
		FORM_DOT,  // «.cmd ...»
		FORM_BARE, // «cmd ...»
	};

	// Команда ли это: имя без триггера, как набрал игрок (регистр и кириллица — как есть).
	typedef bool (*IsKnownFn)(const char *word, Form form, void *ctx);

	// Голые слова, которые в чате чаще пишут не как команду: «nc» (nice) — это noclip,
	// «b» — телепорт на бонус, «hm»/«o» — меню. Посреди рана это ломает ран. С «!», «.» и
	// «/» эти команды работают как раньше.
	bool IsBareDenied(const char *word);

	// text — строка чата без кавычек. true — строку надо заменить на out («!» + слово в
	// нижнем регистре + остаток строки как есть). false — строка не трогается: уже с «!»/«/»,
	// не команда, в ней есть кавычка (не собрать обратно в say "...") или не влезает.
	bool Rewrite(const char *text, IsKnownFn isKnown, void *ctx, char *out, size_t outSize);
} // namespace chattrigger
