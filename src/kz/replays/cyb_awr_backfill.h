/*
 * cyb_awr_backfill — воркер бэклога AWR: берёт у api реплеи без посчитанного
 * AWR-времени, считает разрез телепорт-петель по САМОМУ файлу и отдаёт результат
 * обратно.
 *
 * До N файлов в полёте одновременно (конвар `kz_awr_backfill_concurrency`, дефолт 1,
 * потолок 8): упор прогона — СЕТЬ, файл до 32 МБ качается около секунды, и один файл за раз
 * давал 59 файлов в минуту. Скачивание и разбор параллелятся, а ЗАПРОС бэклога остаётся
 * сериализованным: в нём живёт курсор смещения, и запросы внахлёст гоняли бы его
 * наперегонки. Разбор файла, адаптация кадров и сам разрез — на рабочем потоке (внутри
 * ComputeCutFor), на главном остаются только HTTP и забор результатов; в игровом такте
 * кода нет вовсе.
 *
 * Ручной прогон — консольная команда `kz_awr_backfill <count> [-dry-run]`.
 */
#pragma once

#include "common.h"

namespace CybAwrBackfill
{
	// Регистрация таймера-насоса. Зовётся один раз при загрузке плагина.
	void Init();

	// Выгрузка плагина. Гасит полёты и делает join КАЖДОГО рабочего потока, без таймаута:
	// они держат указатели в наш .so (включая деструкторы замыкания), а выгрузка под живым
	// потоком — падение сервера.
	void Shutdown();

	// Смена карты (Hook_StartupServer). Гасит ВСЕ слоты «файл в полёте»: HTTP-колбэки
	// прошлой карты могут не прийти вовсе или быть отброшены по эпохе, и без сброса воркер
	// молчал бы до перезапуска сервера. Рабочие потоки при этом не трогаются — их результаты
	// отбрасываются по эпохе, а взятие новых файлов гейтится их числом (см. MaybeFetchNext).
	void OnMapChanged();

	// Обработать до `count` файлов бэклога подряд (один файл в секунду).
	// dryRun — посчитать и залогировать, результат в api НЕ отправлять.
	// count == 0 — остановить уже идущий прогон (текущий файл додумывается).
	// В dry-run уже виденные в ЭТОМ прогоне uuid пропускаются (см. .cpp): без пометки в api
	// бэклог отдавал бы один и тот же файл столько раз, сколько попыток запрошено.
	void Run(u32 count, bool dryRun);
} // namespace CybAwrBackfill
