// awr_cut — вырезка телепорт-петель из записанного рана (AWR).
// БЕЗ common.h и SDK: модуль обязан компилироваться голым clang++ (host-тесты
// tests/awr_cut_test.cpp), поэтому здесь uint32_t/int32_t, а не u32/i32 форка.
#pragma once
#include <cstdint>
#include <vector>

namespace KZ::replaysystem::awr
{
	struct Frame
	{
		uint32_t serverTick;
		int32_t cpIndex;     // TickData::checkpoint.index
		int32_t cpCount;     // TickData::checkpoint.checkpointCount
		int32_t tpCount;     // TickData::checkpoint.teleportCount
		float origin[3];     // TickData::post.origin — конец тика
		float preOrigin[3];  // TickData::pre.origin — начало тика
	};

	// Допуск сопоставления позиции прибытия телепорта с кадром, юниты.
	//
	// Побитового совпадения НЕТ и быть не может: KZCheckpointService::SetCheckpoint копирует
	// origin игрока В МОМЕНТ команды (середина тика, игрок обычно на бегу), а в кадре записаны
	// только pre.origin (начало тика) и post.origin (конец). То же у !undo: undoTeleportData
	// хранит позицию на момент команды. Первый живой прогон бэкфилла это и показал —
	// 50 файлов из 50 упали в dest_not_found.
	//
	// 16 юнитов: за один тик при 400 u/s (быстрее в KZ бегают редко) игрок проходит ~6 u, то
	// есть позиция чекпоинта заведомо внутри отрезка pre→post своего кадра, и 16 покрывает его
	// с запасом (+ погрешность позиции после самого телепорта: движок ставит игрока на землю).
	// При этом 16 u — четверть ширины игрока, заведомо меньше расстояния между РАЗНЫМИ местами
	// стояния на маршруте, поэтому чужой чекпоинт под допуск не попадает.
	inline constexpr float AWR_DEST_TOLERANCE = 16.0f;

	// Интервал ИНДЕКСОВ кадров, оба конца включительно.
	struct Interval
	{
		uint32_t from;
		uint32_t to;
	};

	// Интервал в СЕРВЕРНЫХ ТИКАХ, полуинтервал (from, to] — так измеряются паузы и вырезы,
	// когда речь о времени, а не о кадрах. Это АЛИАС, а не отдельный тип: проверки типом
	// НЕТ, он стоит только чтобы сигнатуры читались. Настоящий тип потребовал бы расщепить
	// playback::PauseIntervalsFromEvents на две функции (она одна отдаёт и кадры, и тики,
	// пара PAUSE→RESUME разбирается в одном месте) — цена больше пользы при одном
	// вызывающем на каждую единицу.
	using TickInterval = Interval;

	struct CutResult
	{
		bool ok = false;
		// dest_not_found | counter_mismatch | no_run_window | awr_interval_overflow |
		// awr_record_gap | awr_implausible | empty. Вызывающий может выставить сюда и свою
		// причину отказа до вызова (not_a_run, course_mismatch — commands.cpp).
		// ДЕТЕРМИНИРОВАННЫЕ отказы (первые четыре) — свойство файла: пересчёт тем же кодом
		// даст то же. `awr_record_gap` и `awr_implausible` — МЯГКИЕ: они говорят «этому
		// результату нельзя верить», и после правки нашего кода тот же файл может посчитаться
		// нормально. Бэкфилл их в api не отправляет, чтобы строка осталась в бэклоге
		// (cyb_awr_backfill.cpp, IsSoftFailure).
		const char *reason = "";
		std::vector<Interval> dead;      // мёртвые интервалы, по возрастанию, без пересечений
		uint32_t teleports = 0;          // число прибытий ТП по кадрам
		uint64_t awrMs = 0;              // timeMs - мёртвое время (за вычетом пересечения с паузами); при !ok не используется
		// Разбор отказа для лога (пусто при ok): что именно не сошлось и насколько. Без него
		// живой прогон бэкфилла отвечает только «dest_not_found», и следующий шаг требует
		// ещё одного цикла сборка→канарейка. Фиксированный буфер: структура уходит между
		// потоками воркера бэкфилла.
		char detail[192] = {};
		// Самый большой разрыв записи ВНУТРИ вырезов — разница serverTick между соседними
		// кадрами, НЕ покрытая записанной паузой, — и кадр, на котором он найден. Считается
		// ВСЕГДА, в том числе на успешном пути: это главный измеримый признак того, что в
		// мёртвое время попало время, которого в timeMs нет (см. AWR_MAX_RECORD_GAP_TICKS).
		// Пишется в строку лога бэкфилла и в трассу kz_awr_debug на каждом файле, чтобы
		// распределение разрывов было видно ДО того, как оно испортит результат.
		//
		// maxUncoveredGapMeasured — дошли ли до подсчёта вообще. На РАННИХ отказах (empty,
		// no_run_window, counter_mismatch, dest_not_found, awr_interval_overflow) цикл по
		// вырезам не выполнялся, и ноль в метрике означал бы «разрыва нет» — читателю
		// распределения это соврало бы. Пустой список вырезов (телепортов не было) — НЕ этот
		// случай: там подсчёт прошёл, а разрывов внутри вырезов не бывает по построению,
		// поэтому measured=true и ноль правдив.
		bool maxUncoveredGapMeasured = false;
		uint64_t maxUncoveredGapTicks = 0;
		uint32_t maxUncoveredGapFrame = 0;
	};

	// Трасса одного прибытия телепорта — только для диагностической команды kz_awr_debug.
	// В обычных вызовах не собирается (trace == nullptr): один вектор на файл и никакой
	// работы в горячем пути.
	struct ArrivalTrace
	{
		uint32_t frame = 0;      // T — кадр прибытия
		uint32_t serverTick = 0;
		int32_t cpIndex = 0;
		int32_t cpCount = 0;
		int32_t tpCount = 0;
		float origin[3] = {};    // позиция прибытия
		int64_t dest = -1;       // D; -1 — не нашли или прибытие пропущено
		// 'a' — сшивка по индексу чекпоинта, 'b' — скан назад, '-' — отказ,
		// 's' — прибытие пропущено обходом (лежит внутри уже объявленного выреза).
		char method = 's';
		int64_t cpFrame = -1;    // S — кадр постановки чекпоинта; -1, если индекс не дал кандидата
		float cpPostDist = -1.0f;
		float cpPreDist = -1.0f;
		uint32_t standTicks = 0; // сколько кадров после T игрок остаётся в той же точке
		uint32_t deadFrom = 0;   // объявленный вырез (осмысленно при dest >= 0)
		uint32_t deadTo = 0;
	};

	// Максимальный разрыв записи внутри вырезов, который разрез считает допустимым, в тиках.
	// Больше — отказ `awr_record_gap`.
	//
	// 64 тика = 1 секунда. Обоснование: рекордер пишет кадр КАЖДЫЙ тик физики игрока
	// (RecordTickData_PhysicsSimulatePost), поэтому единственная законная потеря — одиночные
	// тики на хитче сервера, и до секунды она не дотягивает никогда. Разрыв длиннее секунды,
	// не объяснённый записанной паузой, означает, что кадров нет, а время по serverTick
	// прошло: приписать его к мёртвому или к живому нечем, и любое решение будет
	// выдумыванием. Известный источник таких разрывов — `!prac` (там тиков не пишут вовсе),
	// но он закрыт вычетом паузы; остаётся неизвестное (например реконнект с восстановлением
	// рана), и вот его и ловит этот порог — по ИЗМЕРИМОМУ признаку, а не по доле времени.
	inline constexpr uint64_t AWR_MAX_RECORD_GAP_TICKS = 64;

	// Ниже какой доли времени рана результат считается абсурдным и разрез отказывает
	// (reason = "awr_implausible"). 1/100 — это СЕТЬ, а не основной триггер: основной —
	// измеримый `awr_record_gap` выше. Прежний порог 5 % бил бы и по легитимным гриндам
	// (ран, где чекпоинт поставлен через 2 минуты, а последний телепорт за минуту до финиша
	// при часе общего времени, даёт живого ровно 5 %), поэтому оставлено только «явно
	// абсурдное»: живого меньше 1 % полного времени. Отдельно и всегда отказывает `awrMs == 0`
	// при `timeMs > 0` — ноль наружу как валидное значение не отдаём: такая строка выиграла бы
	// минимум по (карта, курс, режим), и игрок увидел бы пустой прыжок в финиш.
	inline constexpr uint64_t AWR_MIN_LIVE_FRACTION_DIVISOR = 100;

	// pauseTicks — записанные паузы в СЕРВЕРНЫХ ТИКАХ: {from = тик TIMER_PAUSE, to = тик
	// TIMER_RESUME}, длительность паузы = to - from. Могут быть пустыми, неупорядоченными и
	// пересекающимися: функция нормализует их сама (сортировка + слияние), как и вырезы —
	// иначе пересечение двух пауз вычиталось бы дважды и `awrMs` оказался бы завышен.
	//
	// Почему в тиках, а не в индексах кадров (было до 10.09): в `!prac` рекордер НЕ пишет тики
	// вовсе (kz_recording.cpp, RecordTickData_PhysicsSimulatePost), а таймер на это время
	// ставится на паузу (kz_prac.cpp → ForcePause → TIMER_PAUSE/TIMER_RESUME). В файле от
	// многоминутной prac-сессии остаётся РАЗРЫВ serverTick между двумя соседними кадрами, а
	// пауза в индексах кадров съёживается в один кадр — её длительность из мёртвого времени
	// не вычиталась, хотя мёртвое время мерится по serverTick и разрыв учитывает целиком.
	// На длинных гриндах (30-100 минут, 700-4000 телепортов) это давало deadMs > timeMs и
	// awrMs = 0. Пересечение с паузой считается ПО ТИКАМ и разрыв покрывает.
	// tickInterval — секунд на серверный тик (ENGINE_FIXED_TICK_INTERVAL = 1/64).
	// runStart/runEnd — окно САМОГО рана в индексах кадров, включительно (кадры TIMER_START и
	// TIMER_END). Окно обязательно: в run-реплее есть ~5 с предзаписи до старта и ~4 с хвоста
	// после финиша (RunRecorder), и телепорт в хвосте («!r» сразу после финиша) без окна
	// объявил бы мёртвым весь ран — awrMs≈0, и такая строка выиграла бы минимум у api.
	// Прибытия вне окна игнорируются, назначение телепорта ищется только в [runStart, T)
	// и с допуском AWR_DEST_TOLERANCE (см. выше).
	// trace (необязателен) — по одной записи на каждое прибытие ТП в окне, для kz_awr_debug.
	CutResult ComputeAwrCut(const Frame *frames, uint32_t count, const TickInterval *pauseTicks, uint32_t pauseTickCount, uint64_t timeMs,
							double tickInterval, uint32_t runStart, uint32_t runEnd, std::vector<ArrivalTrace> *trace = nullptr);

	// Живые интервалы (дополнение dead на [0, count-1]) — нужны !lead.
	std::vector<Interval> LiveIntervals(const std::vector<Interval> &dead, uint32_t count);

	// Сколько ВЫРЕЗАННОГО времени (в серверных тиках) лежит до тика targetTick включительно,
	// за вычетом пересечения с записанными паузами. Нужна перемотке: отображаемое время бота
	// в AWR-режиме = сырое время от старта рана минус паузы минус вырезы, а аккумулятор пауз
	// плейбека паузы уже вычитает — вычесть их дважды нельзя (та же ловушка, что в подсчёте
	// мёртвого времени выше).
	//
	// deadTickSpans — вырезы, переведённые в ТИКИ полуинтервалом (from, to]: from = serverTick
	// кадра ПЕРЕД вырезом (то есть кадра-назначения D), to = serverTick последнего кадра
	// выреза. Ровно так же телескопируется мёртвое время в ComputeAwrCut, поэтому перевод
	// однозначен, а функция остаётся чистой и тестируемой без типов SDK.
	// pauseTicks — как в ComputeAwrCut: {тик TIMER_PAUSE, тик TIMER_RESUME}; порядок и
	// пересечения неважны, функция их нормализует сама.
	uint64_t DeadTicksUpTo(const TickInterval *deadTickSpans, uint32_t deadCount, const TickInterval *pauseTicks, uint32_t pauseTickCount,
						   uint32_t targetTick);
}
