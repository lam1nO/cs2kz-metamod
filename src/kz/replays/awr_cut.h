// awr_cut — вырезка телепорт-петель из записанного рана (AWR).
// БЕЗ common.h и SDK: модуль обязан компилироваться голым clang++ (host-тесты
// tests/awr_cut_test.cpp), поэтому здесь uint32_t/int32_t, а не u32/i32 форка.
#pragma once
#include <cstdint>
#include <vector>

namespace KZ::replaysystem::awr
{
	struct Frame
	{
		uint32_t serverTick;
		int32_t cpIndex;     // TickData::checkpoint.index
		int32_t cpCount;     // TickData::checkpoint.checkpointCount
		int32_t tpCount;     // TickData::checkpoint.teleportCount
		float origin[3];     // TickData::post.origin — конец тика
		float preOrigin[3];  // TickData::pre.origin — начало тика
	};

	// Допуск сопоставления позиции прибытия телепорта с кадром, юниты.
	//
	// Побитового совпадения НЕТ и быть не может: KZCheckpointService::SetCheckpoint копирует
	// origin игрока В МОМЕНТ команды (середина тика, игрок обычно на бегу), а в кадре записаны
	// только pre.origin (начало тика) и post.origin (конец). То же у !undo: undoTeleportData
	// хранит позицию на момент команды. Первый живой прогон бэкфилла это и показал —
	// 50 файлов из 50 упали в dest_not_found.
	//
	// 16 юнитов: за один тик при 400 u/s (быстрее в KZ бегают редко) игрок проходит ~6 u, то
	// есть позиция чекпоинта заведомо внутри отрезка pre→post своего кадра, и 16 покрывает его
	// с запасом (+ погрешность позиции после самого телепорта: движок ставит игрока на землю).
	// При этом 16 u — четверть ширины игрока, заведомо меньше расстояния между РАЗНЫМИ местами
	// стояния на маршруте, поэтому чужой чекпоинт под допуск не попадает.
	inline constexpr float AWR_DEST_TOLERANCE = 16.0f;

	// Интервал ИНДЕКСОВ кадров, оба конца включительно.
	struct Interval
	{
		uint32_t from;
		uint32_t to;
	};

	struct CutResult
	{
		bool ok = false;
		// dest_not_found | counter_mismatch | no_run_window | awr_interval_overflow |
		// awr_record_gap | awr_implausible | empty. Вызывающий может выставить сюда и свою
		// причину отказа до вызова (not_a_run, course_mismatch — commands.cpp).
		// ДЕТЕРМИНИРОВАННЫЕ отказы (первые четыре) — свойство файла: пересчёт тем же кодом
		// даст то же. `awr_record_gap` и `awr_implausible` — МЯГКИЕ: они говорят «этому
		// результату нельзя верить», и после правки нашего кода тот же файл может посчитаться
		// нормально. Бэкфилл их в api не отправляет, чтобы строка осталась в бэклоге
		// (cyb_awr_backfill.cpp, IsSoftFailure).
		const char *reason = "";
		std::vector<Interval> dead;      // мёртвые интервалы, по возрастанию, без пересечений
		uint32_t teleports = 0;          // число прибытий ТП по кадрам
		uint64_t awrMs = 0;              // timeMs - мёртвое время (за вычетом пересечения с паузами); при !ok не используется
		// Разбор отказа для лога (пусто при ok): что именно не сошлось и насколько. Без него
		// живой прогон бэкфилла отвечает только «dest_not_found», и следующий шаг требует
		// ещё одного цикла сборка→канарейка. Фиксированный буфер: структура уходит между
		// потоками воркера бэкфилла.
		char detail[192] = {};
		// Самый большой разрыв ЗАПИСИ внутри вырезов: разница serverTick между соседними
		// кадрами (у здорового реплея она всюду 1) и кадр, на котором она найдена.
		// ДИАГНОСТИКА, а не критерий: с тех пор как мёртвое время считается в КАДРАХ, разрыв
		// на результат не влияет вовсе — неписанный промежуток не даёт вклада ни в timeMs, ни
		// в мёртвое время. Метрика остаётся, потому что по ней видно, сколько времени внутри
		// вырезов не подтверждено кадрами (prac, пауза, смерть), и она же единственная
		// зацепка, если файл окажется битым (см. AWR_MAX_RECORD_GAP_TICKS).
		//
		// maxRecordGapMeasured — дошли ли до подсчёта вообще. На РАННИХ отказах (empty,
		// no_run_window, counter_mismatch, dest_not_found) цикл по вырезам не выполнялся, и
		// ноль в метрике означал бы «разрыва нет» — читателю распределения это соврало бы.
		// Пустой список вырезов (телепортов не было) — НЕ этот случай: там подсчёт прошёл, а
		// разрывов внутри вырезов не бывает по построению, поэтому measured=true и ноль
		// правдив. У awr_interval_overflow подсчёт УЖЕ прошёл (переполнение видно только
		// после него), поэтому там печатается настоящее число, а не n/a.
		bool maxRecordGapMeasured = false;
		uint64_t maxRecordGapTicks = 0;
		uint32_t maxRecordGapFrame = 0;
		// ПРЯМАЯ сверка тождества, на котором стоит вся мера мёртвого времени: число
		// записанных и НЕ паузных кадров окна рана обязано совпадать с числом тиков, которые
		// насчитал таймер (timeMs / tickInterval). Гейты сходятся ровно на это:
		// рекордер пишет кадр при `alive && !prac` (recording/events.cpp, kz_recording.cpp),
		// таймер тикает при `alive && running && !paused` (timer/kz_timer.cpp) — разница
		// только в паузных кадрах, а они вычитаются.
		//
		// Зачем метрика, если есть отказы: `deadMs >= timeMs` ловит завышение мёртвого только
		// после 100 %, сеть 1 % — только абсурд, а завышение на 5-50 % (например паузная пара,
		// порванная посторонним TIMER_START, playback.cpp) даёт ПРАВДОПОДОБНЫЙ заниженный
		// awrMs, то есть чужой проигранный рекорд. Сверка — единственное, что видит этот класс.
		// Отказа она НЕ вызывает намеренно: живой разброс неизвестен, сначала нужно его
		// увидеть (предупреждение в лог с числами), и только потом решать про порог.
		bool timerFramesChecked = false;
		uint64_t timerFramesRecorded = 0;  // кадры окна минус паузные
		uint64_t timerFramesExpected = 0;  // timeMs / tickInterval
		bool timerFramesMismatch = false;  // расхождение сверх допуска (см. AWR_TIMER_FRAMES_TOLERANCE_*)
	};

	// Трасса одного прибытия телепорта — только для диагностической команды kz_awr_debug.
	// В обычных вызовах не собирается (trace == nullptr): один вектор на файл и никакой
	// работы в горячем пути.
	struct ArrivalTrace
	{
		uint32_t frame = 0;      // T — кадр прибытия
		uint32_t serverTick = 0;
		int32_t cpIndex = 0;
		int32_t cpCount = 0;
		int32_t tpCount = 0;
		float origin[3] = {};    // позиция прибытия
		int64_t dest = -1;       // D; -1 — не нашли или прибытие пропущено
		// 'a' — сшивка по индексу чекпоинта, 'b' — скан назад, '-' — отказ,
		// 's' — прибытие пропущено обходом (лежит внутри уже объявленного выреза).
		char method = 's';
		int64_t cpFrame = -1;    // S — кадр постановки чекпоинта; -1, если индекс не дал кандидата
		float cpPostDist = -1.0f;
		float cpPreDist = -1.0f;
		uint32_t standTicks = 0; // сколько кадров после T игрок остаётся в той же точке
		uint32_t deadFrom = 0;   // объявленный вырез (осмысленно при dest >= 0)
		uint32_t deadTo = 0;
	};

	// Максимальный разрыв записи внутри вырезов, при котором файл ещё считается целым, в
	// серверных тиках. Больше — отказ `awr_record_gap`.
	//
	// Это СТРАХОВКА ОТ БИТОГО ФАЙЛА, а не фильтр истории. Прежние 64 тика (секунда) отсекали
	// законные раны: живой замер на канарейке cyb.183 дал 32 мягких отказа из 40 файлов с
	// разрывами от 3.5 с до 2005 с (медиана 30.8 с) — это `!prac` и паузы, а у восьми
	// успевших файлов разрыв был ровно 1 тик. Причина отказов была не в разрывах, а в
	// ЕДИНИЦАХ мёртвого времени: считали серверные тики против тиков ТАЙМЕРА. После перехода
	// на кадры разрыв на результат не влияет, и порог сдвинут туда, куда законная пауза
	// внутри ОДНОГО рана дотянуться не может: час игрового времени. Дотянувшийся разрыв
	// означает уже не паузу, а склеенный или битый файл.
	inline constexpr uint64_t AWR_MAX_RECORD_GAP_TICKS = 64 * 60 * 60;

	// Допуск сверки «кадры окна против тиков таймера»: абсолютный (тиков) и относительный
	// (делитель ожидаемого). Расхождение сверх max(абс, ожидание/делитель) — предупреждение.
	//
	// 16 тиков (0.25 с) — это заведомо больше суммы законных источников: таймер стартует и
	// финиширует с СУБТИКОВЫМ сдвигом (kz_timer.cpp: `currentTime = GetGlobals()->curtime -
	// GetServerGlobals()->curtime`, значение в (-тик, 0]) — до тика на каждом конце; окно
	// рана выводится по кадрам (первый кадр с serverTick >= тика старта, последний с
	// serverTick <= тика финиша) — ещё до кадра на каждом конце; плюс запас на одиночные
	// потерянные тики. Относительный член (1/1000) — на накопление таких потерь в длинных
	// ранах: на 100-минутном ране это 384 тика (6 с). Оба заведомо на порядки меньше класса,
	// который метрика ищет (завышение мёртвого на 5-50 %).
	//
	// Честно про слабость: 16 тиков — примерно вчетверо больше суммы ИЗВЕСТНЫХ источников
	// (~4 тика), то есть запас взят «на глаз». Отказа на этом допуске нет, поэтому цена
	// запаса — только слепое пятно: на ранах короче ~5 секунд 16 тиков перекрывают те самые
	// 5 %, и завышение мёртвого там метрика не увидит. Пересчитывать допуск надо от ЖИВОГО
	// квантиля delta, когда прогон даст распределение (замер cyb.184: delta в -1..0, медиана
	// -1 — то есть реальный разброс на порядок меньше допуска).
	inline constexpr uint64_t AWR_TIMER_FRAMES_TOLERANCE_TICKS = 16;
	inline constexpr uint64_t AWR_TIMER_FRAMES_TOLERANCE_DIVISOR = 1000;

	// Ниже какой доли времени рана результат считается абсурдным и разрез отказывает
	// (reason = "awr_implausible"). 1/100 — это СЕТЬ от абсурда: основной жёсткий отказ —
	// `deadMs >= timeMs` ниже (он ловит настоящую порчу счёта), а `awr_record_gap` после
	// перехода на кадры страхует только от битого файла. Прежний порог 5 % бил бы и по легитимным гриндам
	// (ран, где чекпоинт поставлен через 2 минуты, а последний телепорт за минуту до финиша
	// при часе общего времени, даёт живого ровно 5 %), поэтому оставлено только «явно
	// абсурдное»: живого меньше 1 % полного времени. Отдельно и всегда отказывает `awrMs == 0`
	// при `timeMs > 0` — ноль наружу как валидное значение не отдаём: такая строка выиграла бы
	// минимум по (карта, курс, режим), и игрок увидел бы пустой прыжок в финиш.
	inline constexpr uint64_t AWR_MIN_LIVE_FRACTION_DIVISOR = 100;

	// pauses — записанные паузы в ИНДЕКСАХ КАДРОВ (включительно), могут быть пустыми,
	// неупорядоченными и пересекающимися: функция нормализует их сама (сортировка + слияние),
	// иначе пересечение двух пауз вычлось бы дважды и awrMs оказался бы завышен.
	//
	// Именно в кадрах, а не в тиках (как было 10.09): мёртвое время измеряется ЧИСЛОМ
	// ЗАПИСАННЫХ КАДРОВ, и вычитать из него надо тоже кадры — те, что записаны, пока таймер
	// стоял на паузе (игрок заморожен, но физика симулируется, кадры пишутся). Пауза, во
	// время которой кадров не писали вовсе (`!prac`), в кадрах не существует — и вычитать её
	// не нужно: вклада в мёртвое время у неё и так ноль.
	// tickInterval — секунд на серверный тик (ENGINE_FIXED_TICK_INTERVAL = 1/64).
	// runStart/runEnd — окно САМОГО рана в индексах кадров, включительно (кадры TIMER_START и
	// TIMER_END). Окно обязательно: в run-реплее есть ~5 с предзаписи до старта и ~4 с хвоста
	// после финиша (RunRecorder), и телепорт в хвосте («!r» сразу после финиша) без окна
	// объявил бы мёртвым весь ран — awrMs≈0, и такая строка выиграла бы минимум у api.
	// Прибытия вне окна игнорируются, назначение телепорта ищется только в [runStart, T)
	// и с допуском AWR_DEST_TOLERANCE (см. выше).
	// trace (необязателен) — по одной записи на каждое прибытие ТП в окне, для kz_awr_debug.
	CutResult ComputeAwrCut(const Frame *frames, uint32_t count, const Interval *pauses, uint32_t pauseCount, uint64_t timeMs, double tickInterval,
							uint32_t runStart, uint32_t runEnd, std::vector<ArrivalTrace> *trace = nullptr);

	// Сколько ВЫРЕЗАННЫХ кадров лежит до кадра targetFrame включительно, за вычетом кадров,
	// записанных на паузе. Нужна перемотке: отображаемое время бота в AWR-режиме = сырое
	// время от старта рана до цели минус паузы минус вырезы, а аккумулятор пауз плейбека
	// паузы уже вычитает — вычесть их дважды нельзя (та же ловушка, что в подсчёте мёртвого
	// времени выше).
	//
	// dead и pauses — ИНДЕКСЫ КАДРОВ, включительно; порядок и пересечения неважны. Один
	// записанный кадр = один тик таймера, поэтому вызывающему остаётся умножить результат на
	// длительность тика.
	uint64_t DeadFramesUpTo(const Interval *dead, uint32_t deadCount, const Interval *pauses, uint32_t pauseCount, uint32_t targetFrame);

	// Живые интервалы (дополнение dead на [0, count-1]) — нужны !lead.
	std::vector<Interval> LiveIntervals(const std::vector<Interval> &dead, uint32_t count);
}
