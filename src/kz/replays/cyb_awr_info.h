/*
 * cyb_awr_info.h — `!awr`: время AWR и его автор одной строкой в чат.
 *
 * Запрос владельца серверов дословно: «чтобы не приходилось открывать реплей, чтоб узнать время
 * awr'а». То есть команда НИЧЕГО не качает и не запускает: только резолв метаданных
 * (`CybReplayDownload::RequestInfo`, api `GET /replays/v1/resolve?type=awr`) и печать.
 *
 * Ключ — тот же, что у `!replay awr` и `!lead`: текущая карта, cyber-номер ТЕКУЩЕГО курса
 * игрока, короткое api-имя ТЕКУЩЕГО режима. Аргументов курса/режима у команды НЕТ намеренно,
 * хотя у `!pb`/`!wr` они есть: ключ резолва — это и есть mode-гейт центральных реплеев
 * (см. заголовок cyb_replay_download.h), и `!awr mode=kzt` из vnl пробил бы его в одном месте.
 * Соседние AWR-команды ключом тоже не управляют — ответ `!awr` и следующий за ним `!replay awr`
 * обязаны говорить об одном и том же ране.
 *
 * Почему ДВА резолва. На промахе api отдаёт голый 404 без причины, а промахнуться можно
 * по-разному: (1) файлы на ключе есть, но разрез телепорт-петель по ним ещё не считали — пул
 * `type=awr` берёт только строки с непустым `awr_ms`; (2) на ключе нет вообще ничего. Игроку
 * это разные новости, поэтому 404 по `awr` уточняется вторым резолвом по `wr`: тот отвечает
 * 200, если файл рекордсмена на ключе есть. Уточнение приблизительное — `wr` тоже отдаёт 404,
 * когда рекорд есть, а файла под него нет, — и в этом углу мы скажем «реплеев нет». Цена
 * ошибки здесь нулевая (обе фразы означают «сейчас показать нечего»), а цена третьего запроса
 * на каждый `!awr` — нет.
 */
#pragma once

namespace CybAwrInfo
{
	// Что в итоге печатаем. Порядок не меняется — на нём стоит host-тест.
	enum class Outcome
	{
		Found,       // AWR есть и посчитан: время + автор
		NotComputed, // файлы на ключе есть, разрез ещё не считали
		NoRecord,    // на ключе нет ни одного реплея
		Unavailable, // спросить не смогли: сеть, 5xx, мусор в ответе, резолв выключен
	};

	// ЧИСТАЯ функция: ни SDK, ни состояния — её гоняет host-тест tests/awr_info_test.cpp
	// (сборкой плагина он не собирается, команда в CYBER.md).
	//
	// awrStatus/wrStatus — HTTP-статусы двух резолвов. Ноль = ответа не было вовсе (сетевой
	// отказ), минус один = запроса не было (резолв невозможен по построению). Статус ответа,
	// чьё ТЕЛО оказалось нечитаемым, сюда приезжает настоящим — «2xx с мусором» отбивает
	// вызывающий по CybReplayDownload::Info::bodyUsable, а не эта таблица.
	// wrStatus смотрится ТОЛЬКО когда awr дал 404; во всех остальных случаях он не запрашивается
	// и приезжает нулём — поэтому «awrStatus 2xx» обязан решаться ДО проверок wrStatus.
	//
	// awrHasMs: в ответе было положительное awrMs. У `type=awr` api не отдаёт строк с пустым
	// `awr_ms` вовсе, так что 2xx без времени — это уже расхождение с контрактом; трактуем его
	// как «не посчитан», а не как «нашли ноль»: показывать нулевое время игроку нельзя.
	constexpr Outcome Classify(int awrStatus, bool awrHasMs, int wrStatus)
	{
		if (awrStatus >= 200 && awrStatus < 300)
		{
			return awrHasMs ? Outcome::Found : Outcome::NotComputed;
		}
		if (awrStatus != 404)
		{
			return Outcome::Unavailable;
		}
		if (wrStatus >= 200 && wrStatus < 300)
		{
			return Outcome::NotComputed;
		}
		if (wrStatus == 404)
		{
			return Outcome::NoRecord;
		}
		// wr-резолв сам не доехал: «записей нет» утверждать нечем.
		return Outcome::Unavailable;
	}
} // namespace CybAwrInfo
