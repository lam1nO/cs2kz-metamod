/*
 * kz_lead — `!lead`: луч по ногам сшитого маршрута (по умолчанию AWR), видимый ТОЛЬКО
 * вызвавшему игроку, в скользящем окне вокруг него.
 *
 * Почему окно, а не весь путь: в CS2 у серверных плагинов нет temp-entity лучей, каждый
 * отрезок — сетевая сущность (info_particle_system с ui_annotation_line_segment.vpcf, тот
 * же примитив, что у !measure и рёбер зон). Весь маршрут — это тысячи сущностей, окно —
 * десятки (потолок `cybLeadMaxSegments`, дефолт 384).
 *
 * Видимость только владельцу держится на KZ::quiet::OnCheckTransmit: метка
 * CUSTOM_PARTICLE_SYSTEM_TEAM означает «не видит никто», и обратно в белый список луч
 * возвращает именно OwnsParticle отсюда.
 *
 * Путь режим-зависим (спека §5.1): смена режима или карты гасит луч.
 */
#pragma once

#include "../kz.h"
#include "kz/replays/cyb_replay_download.h"

#include <atomic>
#include <memory>
#include <mutex>
#include <string>
#include <vector>

class KZLeadService : public KZBaseService
{
	using KZBaseService::KZBaseService;

public:
	struct Vertex
	{
		Vector pos;
		bool onGround;
		// ЭФФЕКТИВНЫЙ серверный тик: мёртвые (вырезанные) интервалы в нём не занимают
		// времени. Именно поэтому окно «1 с назад / 6 с вперёд» не спотыкается о стык
		// разреза — по сырым индексам кадров там был бы прыжок на тысячи тиков и окно
		// вырождалось бы в один отрезок.
		u32 tickIdx;
	};

	// Разбор файла на рабочем потоке. Живёт на shared_ptr: игрок может уйти (сервис
	// удалён) раньше, чем поток закончит, — владение общее, use-after-free невозможен.
	struct PendingLoad
	{
		std::mutex mu;
		std::atomic<bool> done {false};
		// Поколение запроса: результат протухшей загрузки (успели выключить и включить
		// снова) отбрасывается на главном потоке.
		u32 generation = 0;
		// Разбор занимает место в бюджете одновременных ПЕРЕСБОРОК: рабочий поток обязан
		// освободить его сам, кто бы ни ушёл первым (игрок, карта, плагин). Ставится на
		// главном потоке до старта потока и больше не меняется.
		bool rebuildBudget = false;
		// Допуск упрощения (юниты), СНЯТЫЙ на главном потоке в момент старта разбора: конвар
		// cyb_lead_rdp правится живьём, и читать его из рабочего потока значило бы читать
		// значение, которое в этот момент меняют. Здесь оно уже зафиксировано.
		f32 rdpTolerance = 0.25f;
		std::vector<Vertex> path;
		const char *failReason = nullptr; // != nullptr — путь не построен
		const char *cutWarn = nullptr;    // разрез не сошёлся, путь без вырезки
	};

	virtual void Reset() override;

	// Смена карты. НЕ Reset: на выделенном сервере KZPlayer::Reset зовётся только с
	// дисконнекта (player_manager.cpp) и с late load (cs2kz.cpp), а Hook_StartupServer
	// игроков не сбрасывает — то же ограничение задокументировано у weapon/hud/zones.
	// Без этого после changelevel остался бы включённый луч с маршрутом ЧУЖОЙ карты, а
	// снятие пошло бы RemoveEntity по хендлам уже мёртвого мира. Сущности здесь не
	// удаляются: мира, которому они принадлежали, больше нет.
	static void OnMapChanged();

	// `!lead` / `!lead pb|wr|awr`: включить, если выключен, иначе выключить.
	void Toggle(CybReplayDownload::Kind kind);
	// `!lead off`, смена карты/режима, дисконнект, телепорт-петля данных. Снимает ЛУЧ; путь
	// остаётся жить, если его держит элемент «Прогресс» худа (см. progress).
	void Disable(const char *reason);

	// Перерисовать отрезки всем, у кого луч включён: колбэк конваров вида (cyb_lead_*) и
	// команда kz_lead_refresh. Путь не трогает — только сущности.
	static void RefreshAllSegments(const char *reason);

	// Пересобрать САМ путь всем, у кого он есть (луч или процент): колбэк cyb_lead_rdp.
	// Допуск упрощения работает на сборке пути, а не на отрисовке, поэтому перерисовкой
	// отрезков его не применить — нужен повторный разбор файла. Файл уже лежит в downloads/,
	// сети это не стоит; разбор уходит на рабочий поток тем же путём, что обычная загрузка.
	static void RebuildAllPaths(const char *reason);

	// Процент пройденного маршрута для элемента худа «Прогресс» (0..100); -1 — пути нет
	// (нет AWR-реплея, идёт загрузка, путь не сошёлся), элемент обязан быть СКРЫТ.
	// Готовое число: считается раз в 32 тика вместе с ближайшей вершиной (UpdateProgress),
	// худ его только читает.
	i32 GetProgressPercent() const
	{
		return this->progressPct;
	}

	// Преф элемента «Прогресс» panorama-худа (mhudLeadProgress) — ВТОРОЙ потребитель того же
	// пути, независимый от луча. Зовётся из KZHUDService::RefreshLayoutPrefs, то есть на
	// загрузке префов игрока и после каждой правки в меню.
	void SetProgressWanted(bool wanted);
	// Путь к готовому файлу из CybReplayDownload::RequestFile (главный поток, колбэк Steam
	// HTTP): отсюда стартует ЧТЕНИЕ и разбор на рабочем потоке — в тике не читаем ничего.
	// Пустая строка — реплея нет.
	void OnFileReady(u32 gen, std::string &&filePath);
	// Готовый путь с рабочего потока (зовётся с ГЛАВНОГО потока, из PollPending).
	void OnPathLoaded(std::vector<Vertex> &&newPath);
	void OnPhysicsSimulatePost();

	void OnTeleport()
	{
		// Телепорт рвёт непрерывность движения — ближайшую вершину ищем заново по всему пути.
		this->resync = true;
	}

	bool OwnsParticle(const CEntityHandle &handle) const;

	bool HasOwnedParticles() const
	{
		return !this->segments.empty();
	}

private:
	void ResetState(bool keepEntities);
	void PollPending();
	// Общий отказ загрузки: защёлка ключа + чат ТОЛЬКО игроку, который её просил.
	// retryable=true — пустой путь из OnFileReady: причина может быть и сетевой (404 от 5xx и
	// от обрыва там неотличимы), поэтому такой отказ получает повторы. retryable=false — отказ
	// РАЗБОРА уже скачанного файла: он детерминированный, повторять нечего, защёлкиваем сразу.
	void OnLoadFailed(bool retryable);
	// Старт резолва и докачки. fromPlayer=false — молчаливая загрузка под элемент худа: в чат
	// не пишем ни строки (ни «строю», ни «нет реплея») — элемент просто остаётся скрытым.
	void RequestPath(CybReplayDownload::Kind kind, bool fromPlayer);
	// Молчаливая загрузка пути под включённый процент, если её ещё никто не начал.
	void ArmProgressPath();
	// Ключ резолва пути — cyber-номер курса и имя режима, РОВНО то, чем
	// CybReplayDownload::BuildKey (replays/cyb_replay_download.cpp:68) выбирает файл. Всё, что
	// значит «под какой курс/режим построен путь», сверяется этим ключом и ничем другим.
	i32 CurrentCourseKey() const;
	const char *CurrentModeName() const;
	// Совпадает ли с текущим ключом игрока ключ ГОТОВОГО пути (pathCourse/modeName)...
	bool PathKeyMatchesCurrent() const;
	// ...и ключ УХОДЯЩЕГО запроса (requestCourse/requestMode).
	bool RequestKeyMatchesCurrent() const;
	// Освободить путь и всё посчитанное из него (луч снимает вызывающий). Незавершённая
	// загрузка протухает — её результат отбросит проверка поколения.
	void ReleasePath();
	// Снять сущности отрезков и построить их заново по УЖЕ загруженному пути (сам путь не
	// пересобирается). Нужна живой правке вида: ассет/CP/потолок читаются при создании
	// сущностей. Без включённого луча — no-op.
	void RefreshSegments(const char *reason);
	// Пометить путь под пересборку (с разбросом по слоту, как RefreshSegments). Саму
	// пересборку начинает дросселированная ветка тика — StartPathRebuild.
	void ArmPathRebuild(const char *reason);
	// Запустить повторный разбор УЖЕ скачанного файла (pathFile) на рабочем потоке. Старый
	// путь при этом живёт и считает процент дальше — его сменит готовый результат.
	void StartPathRebuild();
	// Готовый путь ПЕРЕСБОРКИ (главный поток, PollPending): подменяет вершины на месте. Ключ
	// (pathCourse/modeName) не трогает вовсе — файл тот же, значит и ключ тот же; в чат не
	// пишет и луч не переключает (игрок ничего не набирал).
	void OnPathRebuilt(std::vector<Vertex> &&newPath, f32 builtRdp);
	// Кумулятивные длины пути — один раз на загрузку (см. реализацию: почему по длине).
	void BuildCumulativeLengths();
	void UpdateProgress();
	void UpdateWindow();
	void UpdateNearest(const Vector &origin);
	void ApplyWindow(u32 newFrom, u32 newTo);
	void ClearSegments(bool keepEntities);
	void RebuildOwnedIndex();

	std::vector<Vertex> path;
	// cumLen[i] — длина маршрута от вершины 0 до вершины i (юниты), cumLen.size() == path.size().
	// Процент считается по НЕЙ, а не по номеру вершины: после упрощения RDP вершины стоят
	// неравномерно (см. BuildCumulativeLengths).
	std::vector<f32> cumLen;
	f32 totalLen = 0.0f;
	// Окно: segments[i] — отрезок path[windowFrom + i] → path[windowFrom + i + 1].
	std::vector<CEntityHandle> segments;
	// Те же хендлы, отсортированные, — для двоичного поиска в OwnsParticle (горячий путь
	// CheckTransmit: на каждую помеченную частицу, на каждого получателя). Идиома взята у
	// KZZonesService::showBeams по той же причине.
	std::vector<CEntityHandle> ownedSorted;
	u32 windowFrom = 0, windowTo = 0;
	u32 nearest = 0;
	bool resync = true;
	// Луч рисуется (`!lead`). Путь живёт и без него — под процент в худе, поэтому «включён
	// луч» и «путь построен» больше не одно и то же состояние (раньше было одно поле).
	bool beam = false;
	// Преф элемента «Прогресс» худа включён (SetProgressWanted). Второй держатель пути.
	bool progress = false;
	// Загрузку ждёт ИГРОК (`!lead`), а не элемент худа: только такой результат включает луч
	// и печатает в чат. Молчаливая загрузка процента не пишет ни строки.
	bool beamOnLoad = false;
	// Ключ УХОДЯЩЕГО запроса: резолв и докачка асинхронны (сеть + рабочий поток разбора), и к
	// моменту готовности файла игрок может быть уже на другом курсе/в другом режиме. Путь
	// подписывается ИМЕННО этим ключом, а не тем, что был на момент готовности, — иначе
	// вершины main оказались бы помечены курсом бонуса.
	i32 requestCourse = -1;
	char requestMode[64] {};
	// Защёлка отказа, КЛЮЧЕВАННАЯ (курс+режим): без ключа она гасила бы процент до конца карты
	// и там, где запись есть (у main нет AWR → отказ → игрок ушёл на бонус, а процента нет).
	// -1 в failedCourse = защёлки нет. «Снять по смене ключа» иначе нечем: при пустом пути
	// pathCourse равен -1, и текущий курс нигде не хранится.
	i32 failedCourse = -1;
	char failedMode[64] {};
	// Сколько ещё раз отказ под этим ключом считается РЕТРАЕБЕЛЬНЫМ. RequestFile отдаёт пустой
	// путь и на «записи нет» (404), и на сетевую ошибку — различить их здесь нечем, поэтому
	// первые попытки трактуем как возможную сетевую рябь (пауза + повтор), а исчерпав их,
	// защёлкиваем ключ насмерть. 0 при живом failedCourse = защёлка.
	i32 failRetriesLeft = 0;
	// Пауза перед следующей МОЛЧАЛИВОЙ загрузкой, в проходах дросселированной ветки (один
	// проход = 32 тика). Ставится после отказа и после отброшенного протухшего пути: без неё
	// мигающий ключ (игрок топчется на границе двух курсов) гнал бы резолв и докачку каждые
	// 32 тика. Луч не гейтит: он идёт от явной команды игрока.
	i32 armCooldown = 0;
	// Cyber-номер курса, под который построен путь (KZ::course::GetCyberCourseNumber — ТОТ ЖЕ
	// ключ, которым резолвится реплей). -1 — пути нет. Сменился курс — путь чужой: процент по
	// нему показывал бы долю другого маршрута.
	i32 pathCourse = -1;
	// Процент пройденного маршрута, -1 — нет пути (см. GetProgressPercent).
	i32 progressPct = -1;
	// Сетевая фаза: резолв/докачка уже идут, пути ещё нет. Без этого гейта каждый
	// повторный !lead в окне между Toggle и колбэком заводил бы новый резолв, новую
	// докачку и новый поток разбора.
	bool loading = false;
	u32 ticksSinceUpdate = 0;
	std::shared_ptr<PendingLoad> pending;
	// Файл, из которого построен (или строится) путь — он же вход пересборки под новый допуск.
	// Живёт в кэше downloads/, поэтому повторный разбор сети не стоит и резолва не требует: а
	// значит и ключ (курс+режим) пересобранного пути по построению тот же, что был у пути.
	// Пустая строка — пересобирать нечего.
	std::string pathFile;
	// Допуск упрощения, которым построен текущий путь. Отличается от cyb_lead_rdp — путь
	// устарел. -1 — пути нет.
	f32 pathRdp = -1.0f;
	// Путь помечен под пересборку (правка cyb_lead_rdp), но она ещё не начата: ждёт своего
	// прохода дросселированной ветки (разброс по слоту) и окончания текущей загрузки.
	bool rebuildPending = false;
	// Незавершённая загрузка в pending — ПЕРЕСБОРКА, а не первичная: её результат подменяет
	// путь на месте, а отказ не защёлкивает ключ (под ним есть живой путь).
	bool pendingIsRebuild = false;
	// Задержка перед стартом пересборки, в проходах дросселированной ветки (один проход =
	// 32 тика) — та же единица, что у armCooldown. В тиках разбрасывать мало: у пересборки
	// нет сетевой фазы, которая разносит первичные загрузки сама.
	i32 rebuildDelay = 0;
	u32 generation = 0;
	// Имя режима, под который построен путь (модель «путь режим-зависим»).
	char modeName[64] {};
};
