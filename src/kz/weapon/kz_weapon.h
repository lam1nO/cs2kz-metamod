#pragma once
#include "kz/kz.h"

// Выдача оружия по чат-командам (!ak, !m4, !he, ...) на наших не-global KZ-серверах.
// Отдельный сервис с собственным тумблером kz_weapon_commands: так его дешевле вынести
// в самостоятельный модуль, когда команды понадобятся не только в KZ.
//
// Три вещи, которые делает сервис и которые нельзя разнести по разным местам:
//   1. выдаёт оружие (GiveNamedItem);
//   2. гасит атаку, пока в руках граната — гранату можно держать, но нельзя кинуть,
//      чтобы буст и дым не ломали игру остальным (решение владельца проекта);
//   3. переживает RemoveAllItems из KZPistolService::UpdatePistol на !hideweapon.
//      СМЕНУ КОМАНДЫ выданное НЕ переживает, и это осознанно: вход в команду идёт через
//      суицид+респавн, после него в руках только нож и дефолтный пистолет, поэтому
//      SyncFromHeld законно вычищает записи (он не может отличить наш страйп от того,
//      что игрок сам выбросил всё на G). Хочешь иначе — это отдельное решение с
//      пометкой записей «сняты нами, ждут перевыдачи», а не правка комментария.

// Потолок одновременно отслеживаемых выданных стволов на игрока. Не «сколько влезет в
// слоты», а страховка от роста числа энтити в бесконечном KZ-раунде: выброшенное на G
// лежит до смены карты, а команда выдаёт снова.
#define KZ_MAX_GIVEN_WEAPONS 8

// Слот нужен не для красоты: в CS2 выдача второго предмета в ЗАНЯТЫЙ слот не заменяет
// текущий — новый предмет падает на землю, и поднять его нельзя, потому что слот всё ещё
// занят. Отсюда «пишу !glock, передо мной падает glock, остаюсь с usp». Поэтому перед
// выдачей ствол того же слота снимаем. Гранаты — исключение: их слотов несколько, и
// держать he+flash+smoke одновременно можно и нужно.
enum class WeaponSlotKind
{
	Rifle,
	Pistol,
	Grenade,
};

struct WeaponInfo_t
{
	const char *cmd;       // имя команды без префикса kz_ (в чате: !<cmd>)
	const char *className; // classname сущности для GiveNamedItem
	WeaponSlotKind slot;
};

// Результат выдачи. Не bool: причины отказа игроку показываются разными строками, а
// «сломался движок» обязан ещё и попасть в лог с reason.
// clang-format off
enum class GiveResult
{
	Ok,
	NotAlive,   // мёртв, не в игре или сервис выключен
	LimitHit,   // упёрся в KZ_MAX_GIVEN_WEAPONS
	SlotBusy,   // слот занят и освободить его безопасно не вышло
	Internal,   // нет itemServices или GiveNamedItem вернул nullptr — should-never-happen
};
// clang-format on

// Одна выданная запись. Хранятся ДВА имени, и это не избыточность: движок подменяет
// предмет по команде игрока (CT просит weapon_molotov — получает weapon_incgrenade, за T
// зеркально с !inc). Дедуп обязан сверяться с ЗАПРОШЕННЫМ именем, иначе повторная команда
// его не узнает; сверка «ещё в руках?» — с ФАКТИЧЕСКИМ, иначе запись вычищается каждый
// раз, дедуп промахивается, и потолок не достигается никогда.
struct GivenWeapon_t
{
	CUtlString requested;
	CUtlString actual;
	// Хэндл выданной сущности. Нужен для УБОРКИ: игрок выбрасывает оружие на G, а в KZ
	// раунд не кончается — посмертной уборки нет, и «выдал → выбросил → выдал» при
	// кулдауне команд 0.2с копило бы сущности в мире без предела. Потолок носимого от
	// этого не спасает: выброшенное из списка уходит и Count() его не видит.
	CHandle<CBaseEntity> entity;
};

class KZWeaponService : public KZBaseService
{
	using KZBaseService::KZBaseService;

public:
	static bool Enabled();
	// nullptr, если такой команды нет.
	static const WeaponInfo_t *FindByCommand(const char *cmd);
	static bool IsGrenadeClassName(const char *className);
	// nullptr, если такого classname нет в каталоге (значит выдавали не мы).
	static const WeaponInfo_t *FindByClassName(const char *className);

	// На выделенном сервере KZPlayer::Reset() зовётся с ДИСКОННЕКТА, а не со смены карты
	// (player_manager.cpp; ветка hooks.cpp — listen-server). Смену карты список переживает.
	// Хука спавна у сервиса нет, поэтому чистится он не «на спавне», а при первом же
	// обращении: и GiveWeapon, и UpdatePistol начинают с SyncFromHeld, а после смены карты
	// в руках выданного нет — записи выпадают там.
	virtual void Reset() override;

	// Выдать оружие игроку. Отказы: мёртв/не в игре/сервис выключен, упёрся в потолок
	// KZ_MAX_GIVEN_WEAPONS, внутренняя ошибка движка. Причину печатает вызывающая команда.
	GiveResult GiveWeapon(const WeaponInfo_t &info);

	// Синхронизировать список с тем, что реально в руках. Зовётся ДО RemoveAllItems и
	// первой строкой GiveWeapon: так выброшенное на G оружие выпадает из списка и не
	// возвращается обратно. Заодно убирает из мира выброшенную НАМИ сущность, если её
	// никто не подобрал (у подобранной есть владелец — такую не трогаем).
	void SyncFromHeld();

	// Перевыдать всё выданное. Зовётся ПОСЛЕ RemoveAllItems из UpdatePistol.
	void RegiveGiven();

	// Гасим IN_ATTACK/IN_ATTACK2, пока активное оружие — граната. Гейт только по
	// активному оружию: подобранная с земли граната тоже не должна бросаться.
	void OnProcessUsercmds(PlayerCommand *cmds, int numcmds);

private:
	bool HoldingGrenade();
	// Убрать из мира выброшенную нами и никем не подобранную сущность записи i.
	void RemoveDroppedEntity(i32 index);
	// Освободить слот перед выдачей: снять с игрока оружие того же слота.
	// Ok — слот свободен; SlotBusy — отцепить не вышло (выдавать нельзя, ствол упадёт
	// на пол); Internal — сломались сервисы пешки, слот тут ни при чём.
	GiveResult ClearSlot(WeaponSlotKind slot);

	CUtlVector<GivenWeapon_t> givenWeapons {};
};
