#pragma once
#include "kz/kz.h"
#include "kz/option/pref_registry.h"

#include <string>
#include <vector>

// Обмен настройками ВИДА худа между игроками: снимок, применение с предохранителями, откат.
// Спека: docs/superpowers/specs/2026-09-09-hud-share-design.md (§4 транспорт, §5 предохранители).
// Транспорт короткого кода (таблица HudShares в общей MySQL) и чат-команды — hud_share_commands.cpp.
namespace KZ::hudshare
{
	// Категория реестра, подветка которой И ЕСТЬ состав обмена (спека §5.1: «источник истины —
	// реестр, а не рукописный список»). Тот же ключ регистрирует KZHUDService::InitMenuPrefs().
	constexpr const char *HUD_CATEGORY_KEY = "HUD - Menu Cat Hud";

	// Версия схемы снимка. Поднимать при ЛОМАЮЩЕМ изменении КОДИРОВКИ (разделители, набор
	// типов) — но НЕ при изменении состава ключей: состав ловит отпечаток реестра
	// (GetSchemaFingerprint), см. шапку hud_share.cpp.
	constexpr i32 SNAPSHOT_VERSION = 1;

	// Ключ префа с одним слотом отката (снимок «как было ДО последнего применения»).
	// В обмен сам НЕ входит: его нет в категории HUD, и в блок-лист он добавлен явно.
	constexpr const char *UNDO_PREF_KEY = "hudShareUndo";

	// Откуда пришёл снимок: попадает в лог применения и выбирает фразу игроку.
	enum class Source
	{
		ShareCode = 0, // !hudget <код>
		SpecTake,      // !hudtake / пункт меню «забрать худ наблюдаемого» (соседняя задача)
		Undo,          // !hudundo
		Console,       // выгрузка/вставка настроек текстом (соседняя задача)
	};

	struct ApplyStats
	{
		bool ok {};
		i32 applied {};      // ключей записано из снимка
		i32 defaulted {};    // ключ реестра, которого в снимке нет — записан дефолт пункта
		i32 unknown {};      // ключ снимка, которого нет в белом списке — пропущен
		i32 invalid {};      // значение не прошло валидацию по реестру — не применено
		bool schemaDrift {}; // снимок собран ДРУГИМ составом ключей (отпечаток не совпал)
		bool floored {};     // сработал пол по видимости (спека §5.2)
		// Машинно-читаемая причина ОТКАЗА целиком (ok == false); при ok == true пустая.
		const char *reason {""};
	};

	// Плоский белый список обмениваемых ключей, полученный обходом подветки HUD реестра
	// минус блок-лист спеки §5.1. Пункта, отсутствующего в реестре, в обмене нет физически.
	const std::vector<KZ::prefs::Entry> &GetKeys();

	// CRC32 по именам ключей белого списка В ПОРЯДКЕ реестра. Ловит расхождение СОСТАВА между
	// сборкой, собравшей снимок, и сборкой, применяющей его.
	u32 GetSchemaFingerprint();

	// Снимок настроек худа игрока `from` — годится для ЛЮБОГО игрока, в т.ч. наблюдаемого
	// (читает его optionService, как мимикрия mhudMimicSpec). false — снимать нечего:
	// префы игрока не загружены (тогда «снимок» был бы набором дефолтов, выданным за его худ).
	bool Capture(KZPlayer *from, std::string &out);

	// ЕДИНСТВЕННАЯ точка применения снимка — ею пользуются !hudget, !hudundo, забор худа
	// наблюдаемого и вставка текстом. Делает всё, что требует спека §5:
	//   - разбирает и валидирует снимок ЦЕЛИКОМ до первой записи (полуприменённый худ = «залипший»);
	//   - неизвестные ключи пропускает, битые не применяет — оба случая в лог с reason;
	//   - fail-closed по гейту записи префов (KZOptionService::IsLoaded(), тот же, что открывает
	//     isSetUp в db/setup_client.cpp) — иначе запись молча проглотится;
	//   - пишет всё в ОДНОМ KZOptionService::BatchScope (одна сериализация prefKV, один UPDATE);
	//   - сохраняет слот отката тем же пакетом;
	//   - поднимает пол по видимости, если после импорта не виден ни один элемент;
	//   - зовёт DestroyOwnedLayout() (интерн-пул сущности) и RefreshLayoutPrefs() (кэш префов);
	//   - печатает игроку итог/отказ и логирует его с машинно-читаемым reason.
	// sourceDetail — необязательная деталь для лога (код обмена, steam_id наблюдаемого); NULL можно.
	ApplyStats Apply(KZPlayer *to, const char *snapshot, Source source, const char *sourceDetail);

	// Один слот отката: есть ли что откатывать и откат (тем же Apply, Source::Undo).
	bool HasUndo(KZPlayer *player);
	ApplyStats ApplyUndo(KZPlayer *player);

	// Короткий код обмена: регистронезависимый, без похожих символов (0/O, 1/l/I, 5/S).
	// Нормализация — единственный способ добиться регистронезависимости на ОБЕИХ базах
	// (коллация MySQL нам не гарантирована, у SQLite её нет вовсе).
	constexpr i32 CODE_LENGTH = 6;
	bool NormalizeCode(const char *in, char *out, i32 outLen);
	void GenerateCode(char *out, i32 outLen);

	// Белый список кэшируется и держит указатели на узлы KZ::menu — обнулить на выгрузке.
	void Cleanup();
} // namespace KZ::hudshare
